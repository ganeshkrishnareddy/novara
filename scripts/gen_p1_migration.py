"""Generate one idempotent Alembic revision for P1 module tables.

Usage (from D:\\NOVARA):
  .venv\\Scripts\\python.exe scripts\\gen_p1_migration.py <revision> <down_revision> <table1,table2,...> <slug>

The generated upgrade creates each named table only when it is missing, so a
local dev DB created by Base.metadata.create_all and a fresh DB both converge.
downgrade drops only the tables this revision owns.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API = ROOT / "apps" / "api"
sys.path.insert(0, str(API))


def main() -> None:
    if len(sys.argv) < 5:
        raise SystemExit(__doc__)
    revision, down_revision, tables_arg, slug = sys.argv[1:5]
    tables = [t.strip() for t in tables_arg.split(",") if t.strip()]

    from novara_core.database import Base
    from novara_core.modules import import_all
    import_all()

    missing = [t for t in tables if t not in Base.metadata.tables]
    if missing:
        raise SystemExit(f"Tables not found in Base.metadata: {missing}")

    path = ROOT / "apps" / "api" / "migrations" / "versions" / f"{revision}_{slug}.py"
    cols = "\n".join(f'    "{t}",' for t in tables)
    content = f'''"""P1 capability tables ({slug})

Idempotent migration generated by scripts/gen_p1_migration.py. Local-first
startup creates module tables with Base.metadata.create_all before Alembic
runs, so each table is guarded by a has_table check.

Revision ID: {revision}
Revises: {down_revision}
Create Date: 2026-11-23
"""

from __future__ import annotations

from alembic import op
import sqlalchemy as sa

from novara_core.database import Base
from novara_core.modules import import_all

revision = "{revision}"
down_revision = "{down_revision}"
branch_labels = None
depends_on = None

TABLES = (
{cols}
)


def _tables():
    import_all()
    return {{name: Base.metadata.tables[name] for name in TABLES}}


def upgrade() -> None:
    bind = op.get_bind()
    inspector = sa.inspect(bind)
    for name, table in _tables().items():
        if not inspector.has_table(name):
            table.create(bind)


def downgrade() -> None:
    bind = op.get_bind()
    inspector = sa.inspect(bind)
    for name in reversed(TABLES):
        if inspector.has_table(name):
            op.drop_table(name)
'''
    path.write_text(content, encoding="utf-8")
    print(f"Wrote {path}")
    for t in tables:
        table = Base.metadata.tables[t]
        print(f"  {t}: {len(table.columns)} columns, {len(table.foreign_keys)} FKs")


if __name__ == "__main__":
    main()
