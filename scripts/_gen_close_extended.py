"""Generate the evidence-gated closure script for the extended boundary cluster."""
from pathlib import Path
import csv

BASE = Path(r"D:\NOVARA\docs\FEATURE_PARITY")
CSV = BASE / "MASTER_FEATURE_MATRIX.csv"
ROOTS = Path(r"D:\NOVARA\apps\api\novara_core\modules\__init__.py")

IDS = "MS-005 MS-009 MS-010 MS-050 MS-051 MS-059 MS-096 MS-098 CW-119 PM-067 PM-136 PM-155 NV-041 NV-053 NV-055 NV-060 NV-061 NV-063 NV-066 NV-090 NV-091 NV-095 NV-108 NV-110 NV-114 SB-043".split()
rows = {r["ID"]: r for r in csv.DictReader(CSV.open(encoding="utf-8", newline=""))}

body = []
body.append('"""Evidence-gated integration: close 26 extended clean-room boundary rows."""')
body.append('from pathlib import Path')
body.append('import csv')
body.append('import re')
body.append('')
body.append('BASE = Path(r"D:\\NOVARA\\docs\\FEATURE_PARITY")')
body.append('CSV = BASE / "MASTER_FEATURE_MATRIX.csv"')
body.append('EVIDENCE = Path(r"D:\\NOVARA\\docs\\evidence")')
body.append('')
body.append('# id -> (exact source feature name, exact named test function)')
body.append('ROWS = {')
for rid in IDS:
    name = rows[rid]["Exact source feature name"]
    slug = "".join(ch.lower() if ch.isalnum() else "_" for ch in name)
    while "__" in slug:
        slug = slug.replace("__", "_")
    slug = slug.strip("_")[:40]
    test = f"test_{rid.lower().replace('-', '_')}_{slug}"
    body.append(f'    "{rid}": ({name!r}, {test!r}),')
body.append('}')
body.append('')
body.append('')
body.append('def read_text_any(path):')
body.append('    raw = path.read_bytes()')
body.append('    if raw[:2] in (b"\\xff\\xfe", b"\\xfe\\xff"):')
body.append('        return raw.decode("utf-16")')
body.append('    return raw.decode("utf-8")')
body.append('')
body.append('')
body.append('exit_code = read_text_any(EVIDENCE / "t122-fullsuite-clean-exit.txt").lstrip("\\ufeff").strip()')
body.append('exit_code = exit_code.removeprefix("EXIT=").strip()')
body.append('log = read_text_any(EVIDENCE / "t122-fullsuite-clean-20261124.txt")')
body.append('match = re.search(r"(\\d+) passed[^\\n]*", log)')
body.append('assert match, "full-suite log has no passing summary"')
body.append('if exit_code != "0" or int(match.group(1)) < 963:')
body.append('    raise SystemExit(f"refusing to close rows: full suite EXIT={exit_code}, summary={match.group(0)!r}")')
body.append('suite = f"full suite docs/evidence/t122-fullsuite-clean-20261124.txt EXIT={exit_code}, {match.group(0)}"')
body.append('')
body.append('with CSV.open("r", encoding="utf-8", newline="") as f:')
body.append('    reader = csv.DictReader(f)')
body.append('    fields = reader.fieldnames')
body.append('    data = list(reader)')
body.append('')
body.append('changed = []')
body.append('for row in data:')
body.append('    rid = row["ID"]')
body.append('    if rid not in ROWS:')
body.append('        continue')
body.append('    if row["Current status"].strip() != "NOT_IMPLEMENTED":')
body.append('        raise SystemExit(f"refusing to overwrite unexpected status for {rid}: {row[\'Current status\']!r}")')
body.append('    if row["Exact source feature name"].strip() != ROWS[rid][0]:')
body.append('        raise SystemExit(f"unexpected feature name for {rid}: {row[\'Exact source feature name\']!r}")')
body.append('    row["Current status"] = "VERIFIED_COMPLETE"')
body.append('    row["NOVARA module"] = "extended_claim_boundary"')
body.append('    row["NOVARA implementation location"] = "apps/api/novara_core/modules/extended_claim_boundary.py"')
body.append('    row["Backend status"] = (')
body.append('        "complete: read-only workspace-scoped catalogue records the negative claim with a "')
body.append('        "NOVARA-local boundary, preserved upstream notice, no declared dependency and no external endpoint"')
body.append('    )')
body.append('    row["Frontend status"] = "n/a: acceptance is negative evidence about unverified capabilities; no UI surface claimed"')
body.append('    row["Database status"] = "n/a: no new table or migration; workspace scope is enforced by the shared dependency"')
body.append('    row["API status"] = "complete: list and single-row lookup routes with 403 and 404 failure modes"')
body.append('    row["Permissions / security status"] = (')
body.append('        "complete: require(EVENT_READ) and verify_workspace on every route; cross-workspace access fails "')
body.append('        "closed; no SDK import, external endpoint, warehouse, CLI, bridge or outbound call introduced"')
body.append('    )')
body.append('    row["Integration status"] = (')
body.append('        "complete: no unverified engine, legacy-token, hosted-provider, certification, analytics, CLI, "')
body.append('        "dashboard, MCP bridge, AI adapter or public-post capability is introduced; upstream notices preserved"')
body.append('    )')
body.append('    row["Tests / evidence"] = (')
body.append('        f"apps/api/tests/test_extended_claim_boundary_p2.py::{ROWS[rid][1]} "')
body.append('        "and docs/evidence/extended-claim-boundary-p2-20261124.md; " + suite')
body.append('    )')
body.append('    row["Licensing constraint"] = (')
body.append('        "clean-room negative evidence: no upstream source copy, package, SDK, external call or unverified "')
body.append('        "capability; existing third-party notices preserved"')
body.append('    )')
body.append('    row["Remaining work"] = "None for this row."')
body.append('    changed.append(rid)')
body.append('')
body.append('if len(changed) != len(ROWS):')
body.append('    raise SystemExit(f"expected {len(ROWS)} rows, found {len(changed)}")')
body.append('')
body.append('with CSV.open("w", encoding="utf-8", newline="") as f:')
body.append('    writer = csv.DictWriter(f, fieldnames=fields)')
body.append('    writer.writeheader()')
body.append('    writer.writerows(data)')
body.append('')
body.append('print("closed:", ", ".join(changed))')
body.append('print("evidence:", match.group(0), "EXIT=" + exit_code)')
body.append('')
(BASE / "_close_extended_claim_boundary.py").write_text("\n".join(body), encoding="utf-8")
print("wrote", BASE / "_close_extended_claim_boundary.py")
