rows = [r for r in matrix if r["Source project"] == "GrowthBook" and r["Current status"] == "LICENSING_RESTRICTED"]


def absent_from_sources(token: str) -> bool:
    parts = []
    for m in [ROOT / "apps/api/pyproject.toml", ROOT / "Dockerfile", ROOT / "docker-compose.yml"]:
        if m.is_file():
            parts += [l.strip().lower() for l in m.read_text(encoding="utf-8", errors="replace").splitlines()
                      if l.strip() and not l.strip().startswith("#")]
    skip = {p.name for p in MODULES.glob("*boundary*.py")}
    for s in MODULES.rglob("*.py"):
        if s.name in skip:
            continue
        parts.append(s.read_text(encoding="utf-8", errors="replace").lower())
    for s in [ROOT / "apps/web/index.html", ROOT / "apps/web/app.js"]:
        if s.is_file():
            parts.append(s.read_text(encoding="utf-8", errors="replace").lower())
    return token.lower() not in "\n".join(parts)


selected = []
for r in rows:
    token = r["Exact source feature name"].strip().lower()
    if absent_from_sources(token):
        selected.append((r["ID"], r["Exact source feature name"].strip(), token, r["Final acceptance criteria"].strip()))

print("selected", len(selected), "of", len(rows))


def slugify(name):
    s = "".join(ch.lower() if ch.isalnum() else "_" for ch in name)
    while "__" in s:
        s = s.replace("__", "_")
    return s.strip("_")[:45]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


