def _seed_signals(db, workspace_id):
    count = db.execute(select(func.count(SignalCode.id)).where(
        SignalCode.workspace_id == workspace_id
    )).scalar_one()
    if count:
        return
    for code, label, tier, category in SIGNAL_CATALOG:
        db.add(SignalCode(id=new_id(), workspace_id=workspace_id, code=code,
                          label=label, tier=tier, category=category, active=False))
    db.flush()


def _sending_config(db, workspace_id) -> SendingConfig:
    row = db.execute(select(SendingConfig).where(
        SendingConfig.workspace_id == workspace_id
    )).scalar_one_or_none()
    if row is None:
        row = SendingConfig(id=new_id(), workspace_id=workspace_id, mode="approval",
                            autopilot_opt_in=False, global_paused=False)
        db.add(row)
        db.flush()
    return row


def _signal(db, workspace_id, code) -> SignalCode:
    _seed_signals(db, workspace_id)
    row = db.execute(select(SignalCode).where(
        SignalCode.workspace_id == workspace_id, SignalCode.code == code
    )).scalar_one_or_none()
    if row is None:
        raise HTTPException(status_code=404, detail="signal not found")
    return row


def _suggest_offer(context: dict) -> tuple[str, str]:
    industry = (context.get("industry") or "").strip().lower()
    pain = (context.get("pain") or "").strip().lower()
    budget = (context.get("budget") or "").strip().lower()
    if "churn" in pain or "retention" in pain:
        offer = "A 30-day retention pilot with a success review at day 21."
        rationale = "Retention pain maps to a time-boxed pilot with a measurable checkpoint."
    elif "manual" in pain or "time" in pain or "automation" in pain:
        offer = "An automation starter package with two workflow builds included."
        rationale = "Manual-work pain maps to a scoped automation package with concrete deliverables."
    elif budget in {"low", "small", "tight"}:
        offer = "A monthly starter plan with an annual-switch discount."
        rationale = "A tight budget calls for a low-commitment entry plan with a savings path."
    elif industry:
        offer = f"A tailored {industry} walkthrough with a scoped proof of value."
        rationale = "Industry context supports a tailored walkthrough before any commitment."
    else:
        offer = "A discovery call with a written summary of fit and next steps."
        rationale = "Without researched context the safest offer is a low-pressure discovery call."
    return offer, rationale


