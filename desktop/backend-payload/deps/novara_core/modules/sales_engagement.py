@router.get("/signals", operation_id="listSalesSignals")
def list_signals(workspace_id: str,
                 principal: Principal = Depends(require(CONTACT_READ)),
                 db: Session = Depends(get_db)) -> dict:
    verify_workspace(principal, workspace_id)
    _seed_signals(db, workspace_id)
    db.commit()
    rows = db.execute(select(SignalCode).where(
        SignalCode.workspace_id == workspace_id
    ).order_by(SignalCode.code)).scalars().all()
    return {
        "total": len(rows),
        "free": sum(1 for r in rows if r.tier == "free"),
        "paid": sum(1 for r in rows if r.tier == "paid"),
        "signals": [{"code": r.code, "label": r.label, "tier": r.tier,
                     "category": r.category, "active": r.active} for r in rows],
    }


@router.post("/signals/activate-free", operation_id="activateFreeSignals")
def activate_free(workspace_id: str, body: ConfirmIn,
                  principal: Principal = Depends(require(NOTE_WRITE)),
                  db: Session = Depends(get_db)) -> dict:
    verify_workspace(principal, workspace_id)
    if not body.confirm:
        raise HTTPException(status_code=422, detail="free signal activation requires confirm=true")
    _seed_signals(db, workspace_id)
    rows = db.execute(select(SignalCode).where(
        SignalCode.workspace_id == workspace_id, SignalCode.tier == "free"
    )).scalars().all()
    activated = 0
    for row in rows:
        if not row.active:
            row.active = True
            row.confirmed_by = principal.user.id
            row.confirmed_at = now()
            activated += 1
    db.flush()
    _audit(db, workspace_id, SIGNAL_CHANGED, workspace_id,
           {"activated_free": activated}, principal)
    db.commit()
    return {"activated": activated, "tier": "free"}


@router.post("/signals/{code}/activate", operation_id="activateSignal")
def activate_signal(workspace_id: str, code: str, body: ConfirmIn,
                    principal: Principal = Depends(require(NOTE_WRITE)),
                    db: Session = Depends(get_db)) -> dict:
    verify_workspace(principal, workspace_id)
    row = _signal(db, workspace_id, code)
    if row.tier == "paid" and not body.confirm:
        raise HTTPException(status_code=403, detail="paid signals require explicit operator confirmation")
    if not body.confirm:
        raise HTTPException(status_code=422, detail="activation requires confirm=true")
    row.active = True
    row.confirmed_by = principal.user.id
    row.confirmed_at = now()
    db.flush()
    _audit(db, workspace_id, SIGNAL_CHANGED, row.id,
           {"code": code, "tier": row.tier}, principal)
    db.commit()
    return {"code": row.code, "tier": row.tier, "active": True}


