@router.post("/local-queue/enqueue", status_code=status.HTTP_201_CREATED,
             operation_id="enqueueOutbox")
def enqueue(workspace_id: str, body: EnqueueIn,
            principal: Principal = Depends(require(NOTE_WRITE)),
            db: Session = Depends(get_db)) -> dict:
    verify_workspace(principal, workspace_id)
    draft = _get(db, SalesOutreachDraft, workspace_id, body.draft_id, "draft")
    config = _sending_config(db, workspace_id)
    if config.global_paused:
        raise HTTPException(status_code=409, detail="sending is globally paused")
    inbox_pause = db.execute(select(InboxPause).where(
        InboxPause.workspace_id == workspace_id, InboxPause.inbox_key == body.inbox_key,
        InboxPause.paused.is_(True),
    )).scalar_one_or_none()
    if inbox_pause is not None:
        raise HTTPException(status_code=409, detail=f"inbox {body.inbox_key} is paused")
    rules = db.execute(select(SendRule).where(
        SendRule.workspace_id == workspace_id, SendRule.enabled.is_(True)
    )).scalars().all()
    headers: dict = {}
    for rule in rules:
        if rule.kind == "header":
            headers[rule.config["name"]] = rule.config["value"]
            continue
        if "max_per_day" in rule.config:
            today = now().date().isoformat()
            sent_today = db.execute(select(func.count(OutboxMessage.id)).where(
                OutboxMessage.workspace_id == workspace_id,
                func.date(OutboxMessage.created_at) == today,
            )).scalar_one()
            if sent_today >= rule.config["max_per_day"]:
                raise HTTPException(status_code=422,
                                    detail=f"send rule {rule.name}: daily cap reached")
        if "require_signal" in rule.config:
            signal = _signal(db, workspace_id, rule.config["require_signal"])
            if not signal.active:
                raise HTTPException(status_code=422,
                                    detail=f"send rule {rule.name}: signal {signal.code} is not active")
    autopilot = config.mode == "autopilot" and config.autopilot_opt_in
    row = OutboxMessage(id=new_id(), workspace_id=workspace_id, draft_id=draft.id,
                        campaign_key=draft.campaign_key, recipient=body.recipient,
                        inbox_key=body.inbox_key,
                        status="approved" if autopilot else "awaiting_approval",
                        headers=headers, created_at=now(), updated_at=now())
    db.add(row)
    db.flush()
    _audit(db, workspace_id, OUTBOX_CHANGED, row.id,
           {"status": row.status, "autopilot": autopilot}, principal)
    db.commit()
    return {"id": row.id, "status": row.status, "headers": headers,
            "approval_required": not autopilot, "external_delivery": False}


def _transition(db, workspace_id, message_id, allowed_from, new_status, principal, extra=None):
    row = _get(db, OutboxMessage, workspace_id, message_id, "outbox message")
    if row.status not in allowed_from:
        raise HTTPException(status_code=409,
                            detail=f"cannot move from {row.status} to {new_status}")
    row.status = new_status
    row.updated_at = now()
    db.flush()
    payload = {"status": new_status}
    if extra:
        payload.update(extra)
    _audit(db, workspace_id, OUTBOX_CHANGED, row.id, payload, principal)
    db.commit()
    return {"id": row.id, "status": row.status, "external_delivery": False}


