@router.post("/cohorts/{cohort_id}/evaluate", operation_id="evaluateSalesCohort")
def evaluate_cohort(workspace_id: str, cohort_id: str,
                    principal: Principal = Depends(require(NOTE_WRITE)),
                    db: Session = Depends(get_db)) -> dict:
    verify_workspace(principal, workspace_id)
    cohort = _get(db, SalesCohort, workspace_id, cohort_id, "cohort")
    stmt = select(Lead).where(Lead.workspace_id == workspace_id)
    filters = cohort.filters
    if "status" in filters:
        stmt = stmt.where(Lead.status == filters["status"])
    if "priority" in filters:
        stmt = stmt.where(Lead.priority == filters["priority"])
    if "source" in filters:
        stmt = stmt.where(Lead.source == filters["source"])
    if "min_score" in filters:
        stmt = stmt.where(Lead.score >= filters["min_score"])
    leads = db.execute(stmt.order_by(Lead.score.desc())).scalars().all()
    return {"cohort_id": cohort.id, "matched": len(leads),
            "lead_ids": [l.id for l in leads], "external_calls": False}


