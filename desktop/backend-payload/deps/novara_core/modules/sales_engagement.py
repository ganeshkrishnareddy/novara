"""Signal-driven sales engagement governance (Sellbird P2 cluster).

Clean-room implementation of SB-008/009/010/012 (governed 29-signal catalog
with 26 free signals and explicitly confirmed paid signals), SB-015 (cohort
builder over NOVARA leads), SB-017 (local campaign/sequence drafting),
SB-019 (deterministic offer suggestion), SB-022 (durable local outbox with a
status ladder and approval state), SB-023 (opt-in autopilot, approval by
default), SB-026 (sending status and global/per-inbox pause), SB-028 (local
send-rule and header extension points) and SB-055 (sending mode selection).

No Sellbird source is copied. There is no broker, no outbound email and no
real delivery: the outbox is a durable local queue whose only terminal send
state is an explicitly labelled ``simulated`` dry run. Drafts and offers are
generated by deterministic local templates, never an external AI provider.
"""

