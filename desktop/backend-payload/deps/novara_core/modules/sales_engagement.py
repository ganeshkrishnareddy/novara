class CohortIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    name: str = Field(min_length=1, max_length=120)
    filters: dict = Field(default_factory=dict)

    @field_validator("filters")
    @classmethod
    def _filters(cls, value):
        for key in value:
            if key not in COHORT_FIELDS:
                raise ValueError(f"unsupported cohort filter: {key}")
        if "min_score" in value and not isinstance(value["min_score"], int):
            raise ValueError("min_score must be an integer")
        return value


