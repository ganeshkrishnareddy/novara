@router.post("/drafts/generate", status_code=status.HTTP_201_CREATED,
             operation_id="generateSalesOutreachDrafts")
def generate_drafts(workspace_id: str, body: DraftGenerateIn,
                    principal: Principal = Depends(require(NOTE_WRITE)),
                    db: Session = Depends(get_db)) -> dict:
    verify_workspace(principal, workspace_id)
    cohort_name = None
    if body.cohort_id is not None:
        cohort_name = _get(db, SalesCohort, workspace_id, body.cohort_id, "cohort").name
    offer_text = None
    if body.offer_id is not None:
        offer_text = _get(db, OfferSuggestion, workspace_id, body.offer_id, "offer").offer
    created = []
    for step in range(1, body.steps + 1):
        subject = f"{body.campaign_key} — step {step}"
        lines = [f"## {subject}", ""]
        if cohort_name:
            lines.append(f"Audience: **{cohort_name}** cohort.")
        if step == 1:
            lines.append("Opening note: introduce the problem we solve and ask for a short call.")
        elif step == body.steps:
            lines.append("Closing note: polite break-up email leaving the door open.")
        else:
            lines.append(f"Follow-up {step - 1}: share one concrete proof point and a clear ask.")
        if offer_text:
            lines += ["", f"Offer: {offer_text}"]
        lines += ["", "_Draft generated locally; review and approve before any send._"]
        row = SalesOutreachDraft(id=new_id(), workspace_id=workspace_id,
                            campaign_key=body.campaign_key, sequence_step=step,
                            subject=subject, body_md="\n".join(lines),
                            cohort_id=body.cohort_id, offer_id=body.offer_id,
                            status="draft", created_at=now())
        db.add(row)
        created.append({"id": row.id, "sequence_step": step})
    db.flush()
    _audit(db, workspace_id, DRAFT_CREATED, body.campaign_key,
           {"steps": len(created)}, principal)
    db.commit()
    return {"campaign_key": body.campaign_key, "created": len(created), "drafts": created,
            "generated_by": "local-template", "external_model_calls": False}


