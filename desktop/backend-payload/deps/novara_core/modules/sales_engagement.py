@router.post("/delivery-rules", status_code=status.HTTP_201_CREATED,
             operation_id="createSendRule")
def create_send_rule(workspace_id: str, body: SendRuleIn,
                     principal: Principal = Depends(require(NOTE_WRITE)),
                     db: Session = Depends(get_db)) -> dict:
    verify_workspace(principal, workspace_id)
    if body.kind == "rule":
        allowed = {"max_per_day", "require_signal"}
        if not set(body.config) <= allowed or not body.config:
            raise HTTPException(status_code=422, detail="rule config supports max_per_day and require_signal")
        if "max_per_day" in body.config and (not isinstance(body.config["max_per_day"], int) or body.config["max_per_day"] < 1):
            raise HTTPException(status_code=422, detail="max_per_day must be a positive integer")
    else:
        if not body.config.get("name") or not body.config.get("value"):
            raise HTTPException(status_code=422, detail="header config requires name and value")
    exists = db.execute(select(SendRule.id).where(
        SendRule.workspace_id == workspace_id, SendRule.name == body.name
    )).scalar_one_or_none()
    if exists:
        raise HTTPException(status_code=409, detail="send rule already exists")
    row = SendRule(id=new_id(), workspace_id=workspace_id, name=body.name, kind=body.kind,
                   config=body.config, enabled=body.enabled, created_at=now())
    db.add(row)
    db.flush()
    _audit(db, workspace_id, RULE_CHANGED, row.id, {"kind": body.kind}, principal)
    db.commit()
    return {"id": row.id, "name": row.name, "kind": row.kind}


